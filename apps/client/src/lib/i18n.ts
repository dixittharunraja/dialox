const dictionaries: Record<Language, Dictionary> = { en, hi, ta, es };
const LANGUAGE_KEY = 'dialox.language';
const listeners = new Set<() => void>();

function readLanguage(): Language {
  try {
    const stored = localStorage.getItem(LANGUAGE_KEY);
    if (stored && stored in dictionaries) return stored as Language;
  } catch {
    // Fall through to the default.
  }
  return 'en';
}

export function setLanguage(language: string) {
  if (!(language in dictionaries)) return;
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    // Storage blocked: the choice cannot persist, and the UI stays on the default language.
  }
  document.documentElement.lang = language;
  listeners.forEach((notify) => notify());
}

export function useLanguage(): Language {
  return useSyncExternalStore((notify) => {
    listeners.add(notify);
    return () => listeners.delete(notify);
  }, readLanguage);
}

export function useT() {
  const language = useLanguage();
  return useCallback((key: keyof Dictionary) => dictionaries[language][key], [language]);
}
